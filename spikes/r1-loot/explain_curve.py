"""
定价曲线算法解释 —— 可视化对比
=====================================
目的：让非算法背景的读者能判断「这条曲线合不合理」。

要解决的问题：
    输入：每次击杀的期望产出数量 epk（expected per kill）
    输出：绿宝石价格
    要求：越难拿到的东西越贵

难点在于 epk 的跨度极大：
    雪傀儡雪球  epk = 7.5      （一次杀掉一堆）
    僵尸腐肉    epk = 1.0
    凋灵骷髅头  epk = 0.025    （40 次击杀出 1 个）
    僵尸铁锭    epk = 0.0083   （120 次击杀出 1 个）

最大值 / 最小值 = 7.5 / 0.0083 ≈ 900 倍。
要把这 900 倍的跨度，塞进 1~64 绿宝石这个只有 64 倍的空间里。
"""

import math

PRICE_MIN, PRICE_MAX = 1, 64

# 真实数据（来自 R1 spike 全量扫描）
REAL_ITEMS = [
    ("雪傀儡/雪球",        7.5),
    ("女巫/红石",          6.0),
    ("铁傀儡/铁锭",        4.0),
    ("炽足兽/线",          3.5),
    ("猪/猪排",            2.0),
    ("绵羊/羊肉",          1.5),
    ("僵尸/腐肉",          1.0),
    ("骷髅/箭",            1.0),
    ("北极熊/鳕鱼",        0.75),
    ("女巫/木棍",          0.5714),
    ("末影人/末影珍珠",     0.5),
    ("烈焰人/烈焰棒",       0.5),
    ("潜影贝/潜影壳",       0.5),
    ("蜘蛛/蜘蛛眼",        0.3333),
    ("凋灵骷髅/煤炭",       0.3333),
    ("女巫/发光石粉",       0.2857),
    ("溺尸/铜锭",          0.11),
    ("兔子/兔子脚",        0.10),
    ("史莱姆/黏液球",       0.045),
    ("凋灵骷髅/骷髅头颅",   0.025),
    ("僵尸猪灵/金锭",       0.025),
    ("岩浆怪/岩浆膏",       0.0131),
    ("僵尸/铁锭",          0.0083),
]


def price_linear(epk, C=16.0):
    """方案一：线性反比 Price = C / epk"""
    if epk <= 0:
        return PRICE_MAX
    return max(PRICE_MIN, min(PRICE_MAX, int(C / epk)))


def price_log(epk, cheap=2.0, rare=0.005):
    """
    方案二：对数曲线

    核心思想：人对「稀有度」的感知是倍数关系，不是差值关系。

      腐肉 epk=1.0  →  骷髅头 epk=0.025   相差 40 倍
      腐肉 epk=1.0  →  铁锭   epk=0.0083  相差 120 倍

    如果用差值（线性），1.0 - 0.025 = 0.975 和 1.0 - 0.0083 = 0.9917
    这两个差值几乎一样 —— 线性视角下「40倍稀有」和「120倍稀有」区分不出来。

    取对数后，倍数关系变成差值关系：
      log(40)  = 3.69
      log(120) = 4.79
    差别就出来了。

    公式：
      1. 定两个锚点：
           cheap = 2.0    最便宜的东西大概什么产出水平
           rare  = 0.005  最贵的东西大概什么产出水平
      2. 算 epk 在这个区间里的「对数位置」（0 = 最便宜端, 1 = 最贵端）
           pos = log(cheap / epk) / log(cheap / rare)
      3. 把 pos 线性映射到价格区间
           price = PRICE_MIN + (PRICE_MAX - PRICE_MIN) * pos
    """
    if epk <= 0:
        return None
    epk = max(rare * 0.1, min(cheap * 2, epk))
    span = math.log(cheap / rare)          # log(2/0.005) = log(400) = 5.99
    pos = math.log(cheap / epk) / span
    pos = max(0.0, min(1.0, pos))
    return int(round(PRICE_MIN + (PRICE_MAX - PRICE_MIN) * pos))


def main():
    print("=" * 88)
    print("定价曲线算法说明")
    print("=" * 88)

    print("""
【问题】把「期望产出」换算成「绿宝石价格」，要求越稀有越贵。

  难点：期望产出的跨度是 900 倍（雪球 7.5  vs  僵尸铁锭 0.0083），
        但价格空间只有 64 倍（1 ~ 64 绿宝石）。
        必须做压缩，问题是「怎么压」。
""")

    # ─────────────────────────────────────────
    print("=" * 88)
    print("【方案一】线性反比：Price = 16 / epk")
    print("=" * 88)
    print("""
  最直觉的做法：产出越少，价格越高，成反比。
""")
    print("  %-24s %10s  %8s   %s" % ("物品", "期望产出", "价格", ""))
    print("  " + "-" * 72)
    capped = 0
    for name, epk in REAL_ITEMS:
        p = price_linear(epk)
        bar = "█" * max(1, p // 2)
        flag = ""
        if p >= PRICE_MAX:
            capped += 1
            flag = "  ← 撞上限"
        print("  %-24s %10.4f  %8d   %s%s" % (name, epk, p, bar, flag))

    print("""
  ❌ 问题：%d / %d 个物品全部撞上 64 的价格上限。

     溺尸铜锭(0.11)、史莱姆球(0.045)、骷髅头(0.025)、僵尸铁锭(0.0083)
     —— 稀有度差了 13 倍，价格却一模一样，全是 64。

     原因：反比函数 1/x 在 x 趋近 0 时爆炸式增长。
           epk=0.25 时价格就已经到 64 了，再稀有也没地方涨。
           整个「稀有区间」被压成了一个点。
""" % (capped, len(REAL_ITEMS)))

    # ─────────────────────────────────────────
    print("=" * 88)
    print("【方案二】对数曲线")
    print("=" * 88)
    print("""
  换个思路：人对稀有度的感知是「倍数」，不是「差值」。

    腐肉 1.0  →  骷髅头 0.025    差 40 倍
    腐肉 1.0  →  僵尸铁锭 0.0083 差 120 倍

  用减法看：1.0-0.025=0.975，1.0-0.0083=0.9917 —— 几乎一样，区分不出来
  用倍数看：40 倍 和 120 倍 —— 差别明显

  取对数正好能把「倍数关系」变成「差值关系」：
    log(40)  = 3.69
    log(120) = 4.79        ← 有距离了

  三步走：
    第1步  定两个锚点
             cheap = 2.0    「最便宜档」大概是什么产出水平
             rare  = 0.005  「最贵档」大概是什么产出水平

    第2步  算 epk 落在这个区间的哪个位置（0=最便宜端，1=最贵端）
             pos = log(cheap / epk) / log(cheap / rare)
                 = log(2 / epk)     / log(2 / 0.005)
                 = log(2 / epk)     / 5.99

    第3步  把位置映射到价格
             price = 1 + 63 × pos
""")

    print("  %-24s %10s %8s %8s   %s" % ("物品", "期望产出", "pos", "价格", ""))
    print("  " + "-" * 76)
    for name, epk in REAL_ITEMS:
        e = max(0.0005, min(4.0, epk))
        pos = math.log(2.0 / e) / math.log(2.0 / 0.005)
        pos = max(0.0, min(1.0, pos))
        p = price_log(epk)
        bar = "█" * max(1, p // 2)
        print("  %-24s %10.4f %8.3f %8d   %s" % (name, epk, pos, p, bar))

    print("""
  ✅ 稀有区间被拉开了：
       溺尸铜锭    0.11    → 31
       史莱姆球    0.045   → 41
       骷髅头颅    0.025   → 47
       岩浆膏      0.0131  → 54
       僵尸铁锭    0.0083  → 59
     不再全部挤在 64。
""")

    # ─────────────────────────────────────────
    print("=" * 88)
    print("【关键性质】「每稀有一倍，价格涨多少？」")
    print("=" * 88)
    print("""
  对数曲线有个很好的性质：产出每减半，价格上涨固定的点数。
""")
    print("  %12s → %-12s %10s   %s" % ("产出从", "降到", "价格变化", "说明"))
    print("  " + "-" * 70)
    pairs = [(4.0, 2.0), (2.0, 1.0), (1.0, 0.5), (0.5, 0.25),
             (0.25, 0.125), (0.125, 0.0625), (0.0625, 0.03125),
             (0.03125, 0.015625), (0.015625, 0.0078)]
    for a, b in pairs:
        pa, pb = price_log(a), price_log(b)
        print("  %12.4f → %-12.4f %4d → %-4d  (+%d)" % (a, b, pa, pb, pb - pa))

    print("""
  产出每减半，价格稳定上涨约 7 绿宝石。
  这就是「等比例的稀有度提升 → 等量的价格提升」，符合直觉。

  线性反比则完全不是这样：
""")
    for a, b in pairs[:6]:
        pa, pb = price_linear(a), price_linear(b)
        print("  %12.4f → %-12.4f %4d → %-4d  (+%d)" % (a, b, pa, pb, pb - pa))
    print("""
  涨幅从 +4 → +8 → +16 → +32 一路翻倍，然后突然全部卡死在 64。
""")

    # ─────────────────────────────────────────
    print("=" * 88)
    print("【锚点参数怎么调】")
    print("=" * 88)
    print("""
  两个参数直接决定价格分布，可以按你的手感调。
  ⚠️ 注意方向容易搞反，下面是实测结论（不是推测）：

    cheap（默认 2.0）—— 定义「产出到什么程度算白菜价」
        调大（如 4.0）→ 锚点外移，同一个物品显得「相对更稀有」→ 常见物品变贵
        调小（如 1.0）→ 常见物品变便宜甚至白送

    rare（默认 0.005）—— 定义「产出到什么程度算顶级稀有」
        调小（如 0.001）→ 稀有端拉得更远，现有物品显得「没那么稀有」→ 稀有物品变便宜
        调大（如 0.02） → 稀有端收紧，稀有物品更快撞到价格上限
""")
    print("  不同锚点下的价格对比（★ 实测值）：\n")
    configs = [
        ("默认          cheap=2.0  rare=0.005", 2.0, 0.005),
        ("常见也收费    cheap=4.0  rare=0.005", 4.0, 0.005),
        ("稀有端放宽    cheap=2.0  rare=0.001", 2.0, 0.001),
        ("整体压缩      cheap=1.0  rare=0.02 ", 1.0, 0.02),
    ]
    samples = [("腐肉", 1.0), ("末影珍珠", 0.5), ("蜘蛛眼", 0.333),
               ("铜锭", 0.11), ("骷髅头", 0.025), ("僵尸铁锭", 0.0083)]

    print("  %-36s" % "配置", end="")
    for n, _ in samples:
        print("%10s" % n, end="")
    print()
    print("  " + "-" * 96)
    for label, c, r in configs:
        print("  %-36s" % label, end="")
        for _, epk in samples:
            print("%10d" % price_log(epk, c, r), end="")
        print()

    print("""
  ▸ 「常见也收费」cheap 2.0→4.0：腐肉 8→14，日常物品变贵，稀有物品几乎不变
  ▸ 「稀有端放宽」rare 0.005→0.001：骷髅头 47→37，整体价格下移，稀有物变便宜
  ▸ 「整体压缩」：骷髅头 60、僵尸铁锭 64 撞顶 —— 退化成方案一的毛病，不要用

  👉 如果你想让稀有物品更贵，正确做法不是调 rare，而是 **提高 PRICE_MAX**。
     锚点只决定「相对位置」，价格上限才决定「绝对天花板」。
""")


if __name__ == "__main__":
    main()
