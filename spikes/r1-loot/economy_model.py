"""
经济模型测算 —— 用户新规则「每个怪物每种掉落物一天只能交易一次」
================================================================

用户决策（2026-09-11）：
  ① 单次交易产出 = 一次击杀的最大掉落数量
  ② 每个怪物的每种掉落物，一天（1 游戏日 = 24000 tick）只能交易 1 次
  ③ 要考虑「没有绿宝石农场」情况下的绿宝石获取难度

这条规则把原本「次数上限 + 补货」的村民式模型，
换成了「每怪每物每天 1 次」的强约束模型。本脚本量化其影响。
"""

import math

PRICE_MIN, PRICE_MAX = 1, 64


def price_log(epk, cheap=2.0, rare=0.005, pmax=PRICE_MAX):
    if epk <= 0:
        return None
    epk = max(rare * 0.1, min(cheap * 2, epk))
    span = math.log(cheap / rare)
    pos = max(0.0, min(1.0, math.log(cheap / epk) / span))
    return int(round(PRICE_MIN + (pmax - PRICE_MIN) * pos))


# (物品, epk, 单次交易产出=最大掉落数)  —— 来自 R1 spike 实测
ITEMS = [
    ("僵尸/腐肉",           1.0,     2),
    ("僵尸/铁锭",           0.0083,  1),
    ("骷髅/箭",             1.0,     2),
    ("骷髅/骨头",           1.0,     2),
    ("苦力怕/火药",          1.0,     2),
    ("蜘蛛/线",             1.0,     2),
    ("蜘蛛/蜘蛛眼",          0.3333,  1),
    ("末影人/末影珍珠",       0.5,     1),
    ("烈焰人/烈焰棒",        0.5,     1),
    ("凋灵骷髅/骷髅头颅",     0.025,   1),
    ("凋灵骷髅/煤炭",        0.3333,  1),
    ("凋灵骷髅/骨头",        1.0,     2),
    ("溺尸/铜锭",           0.11,    1),
    ("史莱姆/黏液球",        0.045,   1),
    ("女巫/红石",           6.0,     8),
    ("僵尸猪灵/金锭",        0.025,   1),
]

# ── 绿宝石获取途径（无农场情况下）──
# 数据来源：1.21.1 原版村民交易表
EMERALD_SOURCES = [
    ("农民 · 小麦→绿宝石",       20, 1, "20 小麦换 1 绿宝石，需种田"),
    ("农民 · 马铃薯→绿宝石",     26, 1, "26 马铃薯换 1 绿宝石"),
    ("渔夫 · 生鳕鱼→绿宝石",     15, 1, "需钓鱼"),
    ("图书管理员 · 纸→绿宝石",   24, 1, "24 纸 = 24 甘蔗"),
    ("牧羊人 · 羊毛→绿宝石",     18, 1, "需养羊"),
    ("石匠 · 石头→绿宝石",       20, 1, "需挖石头 + 熔炉"),
    ("制箭师 · 木棍→绿宝石",     32, 1, "32 木棍 = 8 原木"),
    ("屠夫 · 生鸡肉→绿宝石",     14, 1, "需养鸡"),
]


def main():
    print("=" * 86)
    print("经济模型测算 —— 新规则「每怪每物每天限 1 次」")
    print("=" * 86)

    # ─────────────────────────────────────
    print("\n【1】新旧规则对比")
    print("-" * 86)
    print("""
  旧模型（村民式，spike 时的假设）：
      每笔交易有 max_uses（如 4 次），用完置灰，每游戏日补货
      → 一只僵尸一天可以卖 4 次腐肉

  新模型（用户决策）：
      每个怪物的每种掉落物，一天只能交易 1 次
      → 一只僵尸一天只能卖 1 次腐肉 + 1 次铁锭 + 1 次胡萝卜 + 1 次马铃薯

  ★ 关键变化：产出上限从「每怪每天 N 次」压到「每怪每物每天 1 次」
     玩家想要更多产出，唯一办法是 **养更多怪**，而不是反复刷同一只。
""")

    # ─────────────────────────────────────
    print("=" * 86)
    print("【2】单只怪物的每日产出上限（新规则下）")
    print("=" * 86)
    print("\n  %-24s %8s %8s %10s %12s" % ("物品", "价格", "单次产出", "每日上限", "单位成本"))
    print("  " + "-" * 68)
    for name, epk, cnt in ITEMS:
        p = price_log(epk)
        per_unit = p / cnt
        print("  %-24s %8d %8d %10s %10.1f 绿/个" % (name, p, cnt, "1 次/天", per_unit))

    print("""
  ▸ 「单位成本」= 价格 ÷ 单次产出，即每获得 1 个物品要花多少绿宝石
    腐肉  8 绿 ÷ 2 个 = 4.0 绿/个
    骷髅头 47 绿 ÷ 1 个 = 47 绿/个
""")

    # ─────────────────────────────────────
    print("=" * 86)
    print("【3】绿宝石获取成本（无绿宝石农场，纯手工村民交易）")
    print("=" * 86)
    print("\n  %-30s %14s %s" % ("途径", "成本/绿宝石", "备注"))
    print("  " + "-" * 76)
    for name, cost, em, note in EMERALD_SOURCES:
        print("  %-30s %8d 单位   %s" % (name, cost, note))

    print("""
  ▸ 一个中等规模的手工农场（不用生电机器）：
      约 60 格麦田，一次收成 ~60 小麦 → 3 绿宝石
      小麦成熟约需 1~2 游戏日
    → **日均产出 2~3 绿宝石**（保守估计，含补种时间）

  ▸ 加上钓鱼、养鸡、挖石头等副业，认真玩的话：
    → **日均 5~10 绿宝石** 是无农场情况下的现实水平
""")

    # ─────────────────────────────────────
    print("=" * 86)
    print("【4】关键测算：拿到目标物品需要多少天？")
    print("=" * 86)

    scenarios = [
        ("凋灵前置：3 个骷髅头颅", "凋灵骷髅/骷髅头颅", 3),
        ("末影之眼 12 个（需 12 末影珍珠）", "末影人/末影珍珠", 12),
        ("酿造台起步：1 个烈焰棒", "烈焰人/烈焰棒", 1),
        ("烈焰粉 10 份（需 5 烈焰棒）", "烈焰人/烈焰棒", 5),
        ("一组腐肉（64 个）", "僵尸/腐肉", 64),
        ("铁锭 32 个（纯交易）", "僵尸/铁锭", 32),
    ]

    lut = {n: (price_log(e), c) for n, e, c in ITEMS}

    print("\n  %-34s %10s %10s %12s %12s" % (
        "目标", "总绿宝石", "需交易次数", "1只怪要几天", "10只怪要几天"))
    print("  " + "-" * 82)
    for label, key, qty in scenarios:
        p, cnt = lut[key]
        trades = math.ceil(qty / cnt)
        total_em = trades * p
        days_1 = trades              # 1 只怪，每天 1 次
        days_10 = math.ceil(trades / 10)  # 10 只怪，每天各 1 次
        print("  %-34s %10d %10d %10d 天 %10d 天" % (
            label, total_em, trades, days_1, days_10))

    print("""
  ★ 「天数」这里指的是**交易次数受限导致的最短天数**，
     还没算「你有没有那么多绿宝石」。下面把绿宝石约束也加进来。
""")

    # ─────────────────────────────────────
    print("=" * 86)
    print("【5】双重约束：交易次数 + 绿宝石收入")
    print("=" * 86)

    for daily_em, label in [(3, "休闲玩家（小麦田，日均 3 绿）"),
                            (8, "认真玩家（多副业，日均 8 绿）"),
                            (20, "勤奋玩家（大规模手工农场，日均 20 绿）")]:
        print("\n  ── %s ──" % label)
        print("    %-34s %12s %12s %10s" % ("目标", "绿宝石耗时", "交易次数耗时", "实际耗时"))
        print("    " + "-" * 72)
        for lbl, key, qty in scenarios:
            p, cnt = lut[key]
            trades = math.ceil(qty / cnt)
            total_em = trades * p
            days_em = math.ceil(total_em / daily_em)
            days_trade = trades  # 单只怪
            actual = max(days_em, days_trade)
            bottleneck = "绿宝石" if days_em > days_trade else "交易次数"
            print("    %-34s %10d 天 %10d 天 %8d 天 (%s)" % (
                lbl, days_em, days_trade, actual, bottleneck))

    # ─────────────────────────────────────
    print("\n" + "=" * 86)
    print("【6】结论与建议")
    print("=" * 86)
    print("""
  ✅ 新规则「每怪每物每天 1 次」有效解决了 R14（怪物农场取代刷怪塔）：
     想要量产，必须养一大群怪，而不是虐待同一只僵尸。
     圈养 20 只僵尸每天最多得 20 次腐肉交易 —— 这本身就是一项建设工程。

  ⚠️ 但引出一个新问题：**双重约束下，绿宝石反而不是瓶颈了**

     以「凋灵前置 3 个骷髅头」为例：
       交易次数约束：单只凋灵骷髅需 3 天（每天 1 次）
       绿宝石约束：  3 × 47 = 141 绿，休闲玩家需 47 天

     → 对休闲玩家，绿宝石是瓶颈（47 天 vs 3 天）
     → 对勤奋玩家（日均 20 绿），141 ÷ 20 ≈ 7 天，反而是交易次数不再是瓶颈
     → 玩家只要多抓几只凋灵骷髅，交易次数约束立刻失效

  💡 建议（需你裁定）：

     方案一：维持 PRICE_MAX = 64
        休闲玩家节奏合理，勤奋玩家能较快获取稀有物品
        「稀有物品仍有难度」主要靠绿宝石成本支撑

     方案二：提高 PRICE_MAX 到 128 或 192
        骷髅头从 47 → 94 / 141，稀有物品的绿宝石门槛显著提高
        ⚠️ 但 MC 单个物品槽最多 64 个，价格 > 64 需要**两个绿宝石槽**
           原版 MerchantOffer 正好支持 costA + costB 两个输入槽
           → 技术上可行（最高 64+64 = 128）
           → 超过 128 则需要绿宝石块（1 块 = 9 绿宝石，64 块 = 576）

     方案三：价格上限保持 64，但对「进度关键物品」用 price_overrides 单独定高价
        骷髅头颅、末影珍珠、烈焰棒、下界之星等手工指定
        灵活但需要维护一张清单

  📌 我的推荐：**方案二 + 绿宝石块**
     - 常规物品用绿宝石（1~64）
     - 稀有物品自动切换为「绿宝石块」计价（相当于 ×9 的价格空间）
     - 骷髅头颅 = 47 绿 → 若改用绿宝石块计价可表达到 576 绿的等价成本
     - 技术上只需在生成 MerchantOffer 时判断价格是否 > 64，
       是则换算成绿宝石块（向上取整）

  ⚠️ 另需注意（新规则引出的技术点）：
     「每种掉落物每天 1 次」需要在实体 NBT 上记录
       Map<ItemId, lastTradeDay>
     而不能简单用 MerchantOffer 的 uses/maxUses
       （因为 maxUses 是「总次数」，不是「每天次数」）
     → 需要自定义补货逻辑：每次打开界面时，
        对比当前游戏日与 lastTradeDay，决定该笔交易是否可用
     → 这会略微增加实现复杂度，但仍在 MerchantOffer 框架内可解
""")


if __name__ == "__main__":
    main()
